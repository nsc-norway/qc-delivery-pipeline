def validate_mapping(entries):
    mapping = {}
    for dummy, real in entries:
        dummy = dummy.strip().upper()
        real = tuple(s.strip().upper() for s in real)
        if not re.fullmatch(r"[ACGT]{8}", dummy):
            raise ValueError(f"Invalid dummy tag: {dummy!r}")
        if len(real) != 4 or len(set(real)) != 4:
            raise ValueError(f"{dummy}: expected four distinct real sequences")
        if any(not re.fullmatch(r"[ACGT]{8}", s) for s in real):
            raise ValueError(f"{dummy}: real sequences must be 8 A/C/G/T bases")
        if dummy in mapping:
            raise ValueError(f"Duplicate dummy tag in mapping: {dummy}")
        mapping[dummy] = real
    if not mapping:
        raise ValueError("The mapping is empty")
    if set(mapping).intersection(s for real in mapping.values() for s in real):
        raise ValueError("A dummy tag is also a real tag; repeated expansion would be unsafe")
    return mapping


def load_mapping(path=None):
    if path is None:
        rows = csv.reader(io.StringIO(_BUILTIN_DATA))
        return validate_mapping((r[0], r[2:]) for r in rows if r)
    columns = ["Dummy Index Tag"] + [f"Real i7 {i}" for i in range(1, 5)]
    with Path(path).open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or not set(columns).issubset(reader.fieldnames):
            raise ValueError("Mapping CSV requires columns: " + ", ".join(columns))
        return validate_mapping(
            (r[columns[0]], [r[c] for c in columns[1:]]) for r in reader
        )


def expand_text(text, mapping):
    """Return (output text, counts), retaining untouched CSV records exactly."""
    bom = "\ufeff" if text.startswith("\ufeff") else ""
    text = text[len(bom):]
    lines = text.splitlines(keepends=True)
    reader = csv.reader(io.StringIO(text, newline=""), strict=True)
    output = [bom]
    previous_line = 0
    in_data = False
    need_header = False
    index_column = None
    width = None
    sections = 0
    counts = {"input_rows": 0, "expanded_rows": 0, "preserved_rows": 0, "output_rows": 0}
    for row in reader:
        raw = "".join(lines[previous_line:reader.line_num])
        previous_line = reader.line_num
        first = row[0].strip() if row else ""
        section = re.fullmatch(r"\[([^\]]+)\]", first)
        if section and all(not value.strip() for value in row[1:]):
            if need_header:
                raise ValueError("Data section has no column header")
            in_data = section.group(1).casefold() in {"bclconvert_data", "data"}
            need_header = in_data
            index_column = None
            if in_data:
                sections += 1
            output.append(raw)
            continue
        if not in_data or not any(value.strip() for value in row):
            output.append(raw)
            continue
        if need_header:
            names = [value.strip().casefold() for value in row]
            matches = [i for i, name in enumerate(names) if name in {"index", "index1"}]
            if len(matches) != 1:
                raise ValueError("Data header must contain exactly one Index or Index1 column")
            index_column = matches[0]
            width = len(row)
            need_header = False
            output.append(raw)
            continue
        if len(row) != width:
            raise ValueError(
                f"CSV record ending at line {reader.line_num}: expected {width} fields, got {len(row)}"
            )
        counts["input_rows"] += 1
        replacements = mapping.get(row[index_column].strip().upper())
        if replacements is None:
            output.append(raw)
            counts["preserved_rows"] += 1
            counts["output_rows"] += 1
            continue
        counts["expanded_rows"] += 1
        counts["output_rows"] += 4
        # Match this record's line endings, including a missing final newline.
        newline = "\r\n" if raw.endswith("\r\n") else "\n" if raw.endswith("\n") else "\r" if raw.endswith("\r") else None
        fallback = next(("\r\n" if s.endswith("\r\n") else "\n" if s.endswith("\n") else "\r" for s in lines if s.endswith(("\r", "\n"))), "\n")
        for number, sequence in enumerate(replacements):
            expanded = list(row)
            expanded[index_column] = sequence
            buffer = io.StringIO(newline="")
            terminator = newline or fallback
            csv.writer(buffer, lineterminator=terminator).writerow(expanded)
            rendered = buffer.getvalue()
            if newline is None and number == 3:
                rendered = rendered[:-len(terminator)]
            output.append(rendered)
    if not sections:
        raise ValueError("No [BCLConvert_Data] or [Data] section found")
    if need_header:
        raise ValueError("Data section has no column header")
    return "".join(output), counts


